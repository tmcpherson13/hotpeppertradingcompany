// Helper function to generate slug from name
function generateId(name: string): string {
  return name.toLowerCase()
    .replace(/[áàâäã]/g, 'a')
    .replace(/[éèêë]/g, 'e')
    .replace(/[íìîï]/g, 'i')
    .replace(/[óòôöõ]/g, 'o')
    .replace(/[úùûü]/g, 'u')
    .replace(/ñ/g, 'n')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

// Helper to extract species code from scientific name
function extractSpecies(scientificName: string): Species {
  if (scientificName.includes('chinense')) return 'chinense';
  if (scientificName.includes('frutescens')) return 'frutescens';
  if (scientificName.includes('baccatum')) return 'baccatum';
  if (scientificName.includes('pubescens')) return 'pubescens';
  // Ancestral species
  if (scientificName.includes('chacoense')) return 'chacoense';
  if (scientificName.includes('galapagoense')) return 'galapagoense';
  if (scientificName.includes('praetermissum')) return 'praetermissum';
  if (scientificName.includes('eximium')) return 'eximium';
  if (scientificName.includes('tovarii')) return 'tovarii';
  if (scientificName.includes('cardenasii')) return 'cardenasii';
  if (scientificName.includes('glabriusculum')) return 'glabriusculum';
  if (scientificName.includes('rhomboideum')) return 'rhomboideum';
  return 'annuum';
}

// Helper to map region from provenance
function mapRegion(provenance: string): 'Americas' | 'Asia' | 'Africa' | 'Europe' | 'Middle East' {
  const prov = provenance.toLowerCase();
  if (prov.includes('asia') || prov.includes('china') || prov.includes('india') || prov.includes('thailand') || prov.includes('korea') || prov.includes('japan') || prov.includes('philippines') || prov.includes('malaysia') || prov.includes('bangladesh')) return 'Asia';
  if (prov.includes('africa') || prov.includes('mozambique') || prov.includes('malawi') || prov.includes('ghana')) return 'Africa';
  if (prov.includes('europe') || prov.includes('italy') || prov.includes('france') || prov.includes('spain') || prov.includes('hungary') || prov.includes('uk')) return 'Europe';
  if (prov.includes('middle east') || prov.includes('syria') || prov.includes('turkey')) return 'Middle East';
  return 'Americas';
}

